public void refreshData() {
    model.Pengguna user = new controller.AuthController().getPenggunaLogin();
    if (user == null) return;

    java.util.List<Object[]> data = new dao.HasilBelajarDao().getRiwayatPelajar(user.getIdPengguna());

    int total = (int) 0L, max = 0, min = Integer.MAX_VALUE;
    for (Object[] r : data) {
        int skor = ((Number) r[2]).intValue();
        total += skor;
        max = Math.max(max, skor);
        min = Math.min(min, skor);
    }
    String rata = data.isEmpty() ? "-" : String.valueOf(Math.round((double) total / data.size()));
    String tinggi = data.isEmpty() ? "-" : String.valueOf(max);
    String rendah = data.isEmpty() ? "-" : String.valueOf(min);

    lblUser.setText("Halo, " + user.getNama() + "!");
    lblTotal.setText("Lanjutkan belajarmu hari ini.");
    lblTotalpelajar.setText(rata);
    lblTotalmateri.setText(tinggi);
    lblTotalkelas.setText(rendah);

    isiTabel(tblRiwayatpelajar, data);
}

private void isiTabel(javax.swing.JTable tabel, java.util.List<Object[]> data) {
    javax.swing.table.DefaultTableModel m = (javax.swing.table.DefaultTableModel) tabel.getModel();
    m.setRowCount(0);
    for (int i = 0; i < Math.min(5, data.size()); i++) {   // 5 terbaru
        Object[] r = data.get(i);
        m.addRow(new Object[]{r[1], r[0], r[2]});          // Paket Soal, Tanggal, Nilai
    }

    }

